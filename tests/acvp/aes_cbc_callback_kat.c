int
main (void)
{
  ngi541_status_t status;
  int result;

  status = ngi541_engine_init ();

  if (status != NGI541_STATUS_OK)
    {
      fprintf (
        stderr,
        "ngi541_engine_init failed: status=%d\n",
        (int) status);

      return 1;
    }

  result = test_encrypt ();

  if (result != 0)
    return 10 + result;

  result = test_decrypt ();

  if (result != 0)
    return 20 + result;

  return 0;
}